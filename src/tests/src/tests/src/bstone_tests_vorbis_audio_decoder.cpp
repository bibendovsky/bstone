constexpr int fixture_frame_count = 2000;
constexpr int fixture_frame_rate = 8000;

// Serves the fixture in bounded chunks so the decoder has to stream.
class FixtureStream final : public bstone::VfsInputStream
{
public:
	explicit FixtureStream(int max_chunk_size)
		:
		max_chunk_size_{max_chunk_size}
	{}

	int get_pathname_index() const override
	{
		return 0;
	}

	int get_size() override
	{
		return static_cast<int>(sizeof(vorbis_fixture));
	}

	bool rewind() override
	{
		position_ = 0;
		return true;
	}

	int read(void* buffer, int buffer_size) override
	{
		const int remaining_size = static_cast<int>(sizeof(vorbis_fixture)) - position_;
		const int read_size = std::min(std::min(buffer_size, remaining_size), max_chunk_size_);
		if (read_size <= 0)
		{
			return 0;
		}
		std::memcpy(buffer, vorbis_fixture + position_, read_size);
		position_ += read_size;
		return read_size;
	}

private:
	int max_chunk_size_{};
	int position_{};
};

struct DecodeResult
{
	int frame_count;
	float peak;
};

bstone::AudioDecoderUPtr open_decoder(int max_chunk_size, int dst_rate)
{
	bstone::VfsInputStreamUPtr stream = std::make_unique<FixtureStream>(max_chunk_size);
	auto decoder = bstone::make_vorbis_audio_decoder();
	const auto param = bstone::AudioDecoderInitParam{
		.vfs_stream = std::move(stream),
		.src_raw_data = nullptr,
		.src_raw_size = 0,
		.dst_rate = dst_rate};
	if (!decoder->initialize(param))
	{
		return nullptr;
	}
	return decoder;
}

DecodeResult decode_all(bstone::AudioDecoder& decoder)
{
	constexpr int max_frames = 1024;
	const int channel_count = decoder.get_channel_count();
	std::vector<float> samples(static_cast<std::size_t>(max_frames) * channel_count);
	DecodeResult result{};
	while (true)
	{
		const int frame_count = decoder.decode_frames(samples.data(), max_frames);
		if (frame_count <= 0)
		{
			break;
		}
		result.frame_count += frame_count;
		for (int i = 0; i < frame_count * channel_count; ++i)
		{
			result.peak = std::max(result.peak, std::abs(samples[i]));
		}
	}
	return result;
}

// initialize(const AudioDecoderInitParam&) / decode_frames(float*, int)
void test_vd8s2k1qw9x0mnp4()
{
	const auto decoder = open_decoder(1 << 30, fixture_frame_rate);
	tester.check(decoder != nullptr);
	tester.check(decoder->get_channel_count() == 1);
	const DecodeResult result = decode_all(*decoder);
	tester.check(result.frame_count >= 1000 && result.frame_count <= 6000);
	tester.check(result.peak > 0.5F);
}

// rewind()
void test_re3jb7nq2m8ttz5c()
{
	const auto decoder = open_decoder(1 << 30, fixture_frame_rate);
	tester.check(decoder != nullptr);
	const DecodeResult first = decode_all(*decoder);
	tester.check(decoder->rewind());
	const DecodeResult second = decode_all(*decoder);
	tester.check(first.frame_count > 0);
	tester.check(second.frame_count == first.frame_count);
}

// decode_frames(float*, int)
// Reads arrive a few bytes at a time.
void test_ch7k0p2vw4y9q1sd()
{
	const auto whole_decoder = open_decoder(1 << 30, fixture_frame_rate);
	const auto chunked_decoder = open_decoder(7, fixture_frame_rate);
	tester.check(whole_decoder != nullptr && chunked_decoder != nullptr);
	const DecodeResult whole = decode_all(*whole_decoder);
	const DecodeResult chunked = decode_all(*chunked_decoder);
	tester.check(whole.frame_count > 0);
	tester.check(chunked.frame_count == whole.frame_count);
}

// decode_frames(float*, int)
// Resampling to a doubled rate.
void test_rs5m1x8zj3w6qn2v()
{
	const auto decoder = open_decoder(1 << 30, fixture_frame_rate);
	const auto resampling_decoder = open_decoder(1 << 30, 2 * fixture_frame_rate);
	tester.check(decoder != nullptr && resampling_decoder != nullptr);
	const DecodeResult as_is = decode_all(*decoder);
	const DecodeResult resampled = decode_all(*resampling_decoder);
	const int expected_frame_count = 2 * as_is.frame_count;
	tester.check(resampled.frame_count >= expected_frame_count - 8);
	tester.check(resampled.frame_count <= expected_frame_count + 8);
}

